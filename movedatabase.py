def clearRecord():
	moveRecord.clear()

def takeBack():
	moveRecord.pop()

def openingComment(piece, destination):
	'''any comment about an opening move ?'''
	# a dummy move ?
	if piece == CK.SQ_EMPTY:
		return None

	lastmove = f"{piece}{destination}"
	moveRecord.append( lastmove )

	# do we have any comment ?
	# - we're not going to go beyond a fixed number of moves for either side
	if len(moveRecord) <= MDB_MAXMOVES:
		ndx = "".join( moveRecord )
		if ndx in moveMDB:
			return moveMDB[ ndx ]

	return None

